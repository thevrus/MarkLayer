import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '../../..');

/** The stylesheets whose `@theme` declares `--text-*` steps. */
const SOURCES = [
  'packages/tokens/theme.css',
  'apps/worker/web/style.css',
  'apps/site/src/styles/global.css',
  'apps/extension/entrypoints/content/style.css',
];

/** Step names in declaration order, deduped. `--text-x--line-height` rides its step and is not one. */
export function typeScale(): string[] {
  const names = new Set<string>();
  for (const file of SOURCES) {
    const css = readFileSync(resolve(root, file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
    for (const [, name] of css.matchAll(/^\s*--text-([a-z][a-z0-9-]*?):\s*(?!initial)/gm)) {
      if (name && !name.includes('--')) names.add(name);
    }
  }
  return [...names];
}

export function render(names: string[]): string {
  const body = names.map((name) => `  '${name}',`).join('\n');
  return `// GENERATED by \`bun run gen:type-scale\` in packages/ui from the \`--text-*\` steps in the @theme blocks. Do not edit.\nexport const TEXT_STEPS = [\n${body}\n];\n`;
}

if (import.meta.main) {
  const { writeFileSync } = await import('node:fs');
  writeFileSync(resolve(import.meta.dir, '../src/type-scale.generated.ts'), render(typeScale()));
}
